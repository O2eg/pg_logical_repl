CREATE SCHEMA lc;
REVOKE ALL ON SCHEMA lc FROM PUBLIC;
CREATE TABLE lc.control (
    migration_id text PRIMARY KEY,
    ownership_token text NOT NULL,
    state text NOT NULL,
    ddl_mode text NOT NULL DEFAULT 'frozen',
    resource_version integer NOT NULL DEFAULT 2,
    settings jsonb NOT NULL DEFAULT '{}',
    updated_at timestamptz NOT NULL DEFAULT clock_timestamp()
);
CREATE TABLE lc.operations (
    name text PRIMARY KEY,
    completed_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    details jsonb NOT NULL DEFAULT '{}'
);
CREATE TABLE lc.ddl_log (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    migration_id text NOT NULL,
    statement text NOT NULL,
    statement_sha256 text NOT NULL,
    context jsonb NOT NULL,
    operation_key text UNIQUE,
    capture_version integer NOT NULL DEFAULT 2,
    source_xid bigint NOT NULL DEFAULT txid_current(),
    command_tag text NOT NULL DEFAULT '',
    actions jsonb NOT NULL DEFAULT '[]',
    queue_jobs jsonb NOT NULL DEFAULT '[]',
    payload_sha256 text NOT NULL DEFAULT '',
    captured_at timestamptz NOT NULL DEFAULT clock_timestamp()
);
CREATE TABLE lc.ddl_applied (
    id bigint PRIMARY KEY,
    statement_sha256 text NOT NULL,
    applied_at timestamptz NOT NULL DEFAULT clock_timestamp()
);
CREATE TABLE lc.ddl_queue (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    ddl_log_id bigint NOT NULL,
    seq integer NOT NULL,
    kind text NOT NULL,
    statement text NOT NULL,
    details jsonb NOT NULL DEFAULT '{}',
    status text NOT NULL DEFAULT 'pending' CHECK(status IN ('pending','running','done','failed','skipped')),
    attempts integer NOT NULL DEFAULT 0,
    last_error text,
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    started_at timestamptz,
    finished_at timestamptz,
    UNIQUE(ddl_log_id,seq)
);
CREATE TABLE lc.table_sync (
    relation_oid oid PRIMARY KEY,
    schema_name text NOT NULL,
    table_name text NOT NULL,
    ddl_log_id bigint NOT NULL,
    state text NOT NULL DEFAULT 'pending_refresh',
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    ready_at timestamptz
);
CREATE TABLE lc.barrier (
    token uuid PRIMARY KEY,
    kind text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT clock_timestamp()
);
REVOKE ALL ON ALL TABLES IN SCHEMA lc FROM PUBLIC;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA lc FROM PUBLIC;
